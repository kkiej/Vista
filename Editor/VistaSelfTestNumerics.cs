using UnityEngine;

namespace Vista.Editor
{
    /// <summary>
    /// 多个自检共用的数值事实。
    ///
    /// 为什么要有这个文件：本项目有一条贯穿始终的规矩 ——
    /// **同一个量不允许存在两份实现**。<c>HalfUlp</c> 是一条纯数值事实，
    /// <c>k_ReadbackFloor</c> 是一条**实测**常量；两者一旦在两个自检里各写一份，
    /// 就会出现「一边更新了、另一边没更新」的状态，而那种偏差的症状恰好是
    /// 「某一条判据的门限比另一条松」—— 最难被发现的一类。
    ///
    /// 这里只放**跨自检共享**的东西。某条自检自己的布景常量、放大系数、
    /// 档位编号一律留在它自己的文件里：把它们集中过来只会让每条自检
    /// 都要去别处才能读懂自己的门限。
    /// </summary>
    static class VistaSelfTestNumerics
    {
        /// <summary>
        /// 渲染 → 读回路径的加性扰动幅度，实测值 = 1/1024。
        ///
        /// 怎么量到的：在 <c>VistaLitAccumulationSelfTest</c> 的 5 档里写死
        /// (0.25, 0.5, 0.75) 这三个 half 精确值，读回来逐像素低 1~2 个 half ulp，
        /// 且随像素位置变化，全图最大偏离恰好是 9.766e-4。
        /// 也就是说着色器写出的值与 CPU 读到的值之间存在一个**加性**扰动场。
        ///
        /// 为什么这条常量值得单独存在：期望值为 0 的量（相对误差、差值的分子）
        /// 读回来永远被这条地板顶起来，而它的量级又与 fp16 相对精度
        /// （<see cref="k_Fp16Rel"/> = 4.88e-4）几乎相同 —— 累加自检的判据 1
        /// 因此连续多次报出 6.595E-004，我却把尺子的地板当成了被测对象的精度极限。
        /// 教训：**尺子的地板与被测量的期望值同量级时，尺子会自己伪造一个结论。**
        /// 修法不是放宽容差（那会把 1e-3 量级的真实偏差一起放过），
        /// 而是在写出之前把被测量抬到地板之上。
        ///
        /// ── 一条重要的性质：它在「同像素两次渲染之差」里会抵消 ──
        ///
        /// 实测它随**像素位置**变化、在恒定值上也变化，也就是说它是一个
        /// 位置的函数而不是值的函数。于是两次渲染在同一像素上相减时，
        /// 同一个扰动量出现在被减数与减数里，一阶上抵消。
        /// 这是 #15 判据②「同一变体渲两遍」那个对照存在的理由：
        /// 对照读到 0，就证明了抵消成立，A-vs-B 的差异不必为这条地板买单。
        /// 反过来，若这条场其实还带一个**值相关**的分量，对照无法把它区分出来 ——
        /// 那一部分由 fp16 量化项负责兜住。
        ///
        /// ── 它可能不是一个「扰动场」 ──
        /// 这个实测值与 <see cref="k_Fp16RelTrunc"/>（fp16 截断的上界 2⁻¹⁰）逐位相同，
        /// 而上面记的现象是「逐像素**低** 1~2 个 ulp」—— 单边偏低正是截断的签名。
        /// #21 在计算着色器 UAV 那条路径上已经把截断实测出来了。这条是否同源、
        /// 「随像素位置变化」那一部分又从哪来，仍未归因；在归因之前不合并两条常量。
        /// </summary>
        public const float k_ReadbackFloor = 9.766e-4f;

        /// <summary>
        /// fp16 **就近取整**时的相对误差上界 = 2⁻¹¹。
        ///
        /// 口径要说清：half 有 10 位尾数，[1,2) 这一档的 ulp 是 2⁻¹⁰；就近取整的绝对
        /// 误差 ≤ ulp/2 = 2⁻¹¹，除以 |v| ≥ 1 得相对上界 2⁻¹¹。也就是说这个数**本身**
        /// 就是「一次舍入」的上界，不是它的两倍 —— 早先这里写的「误差上界是它的一半」
        /// 是错的，会让按它摆的门比自己以为的紧一倍。
        ///
        /// 只在**存储路径确实就近取整**时才是地板。计算着色器的类型化 UAV 存储
        /// 实测是截断的，那条路径要用 <see cref="k_Fp16RelTrunc"/>。
        /// </summary>
        public const float k_Fp16Rel = 4.8828125e-4f;

        /// <summary>
        /// fp16 **截断（向零取整）**时的相对误差上界 = 2⁻¹⁰ —— 整个 ulp，是
        /// <see cref="k_Fp16Rel"/> 的两倍。
        ///
        /// 这不是一条理论保守值，是实测出来的取整模式。证据（#21 的 ⓪ 格，
        /// D3D11 / RTX 3060，计算着色器写 <c>RWTexture3D&lt;float4&gt;</c>，
        /// 格式 R16G16B16A16_SFloat）：12 个请求值/读回值对里，读回值**全部**等于
        /// 请求值下方最近的 half 网格点；其中 3 对的「截断」与「就近」结论不同，
        /// 而 GPU 三次都取了截断 ——
        ///   D 档 S_r：请求 132.359735，ulp 0.125，落在格间 0.878 处
        ///             ⇒ 截断 132.25（= 读回）／就近 132.375；
        ///   F 档 S_r：请求 16.2935517，格间 0.787 ⇒ 截断 16.28125（= 读回）／就近 16.296875；
        ///   F 档 σ_t：请求 0.0162935517，ulp 2⁻¹⁶，格间 0.814
        ///             ⇒ 截断 0.0162811279（= 读回）／就近 0.0162963867。
        /// 三条都是「就近取整会给出另一个答案」的样本，所以这条结论不是巧合。
        ///
        /// 为什么必须单独立一条常量、而不是把 <c>k_Fp16Rel</c> 改大：两者是**两个不同的量**
        /// （两种取整模式各自的上界），不是同一个量的两份实现。而且我只量到了
        /// 计算着色器 UAV 这一条路径 —— 片元着色器经 ROP 写 RT、CopyTexture、
        /// AsyncGPUReadback 各自的取整模式都没测。把 k_Fp16Rel 全局改大，等于拿一条
        /// 路径的实测去放宽五条自检的门，那是在没有证据的地方主动丢掉拒绝力。
        ///
        /// ── 一条待归因的巧合 ──
        /// <see cref="k_ReadbackFloor"/> 的实测值 9.766e-4 与这条常量**逐位相同**，
        /// 且那条的描述里写的是「读回来逐像素**低** 1~2 个 half ulp」—— 同样是单边偏低。
        /// 很可能是同一个截断现象在另一条路径上的显现。但那条同时观察到「随像素位置
        /// 变化」，纯截断一个常量不会有这个性质，所以两者暂不合并：这是一条待做的归因，
        /// 不是一条已经成立的结论。
        /// </summary>
        public const float k_Fp16RelTrunc = 9.765625e-4f;

        /// <summary>
        /// half 在 v 附近的一个 ulp。用来回答「差了几个最小可表示单位」。
        /// </summary>
        public static float HalfUlp(float v)
        {
            v = Mathf.Abs(v);
            const float minNormal = 6.1035156e-5f;    // 2^-14
            const float denormStep = 5.9604645e-8f;   // 2^-24
            if (v < minNormal) return denormStep;
            int e = Mathf.FloorToInt(Mathf.Log(v, 2f));
            return Mathf.Pow(2f, e - 10);             // half 有 10 位尾数
        }

        /// <summary>
        /// fp32 在 v 附近的一个 ulp。
        ///
        /// 为什么两条 ulp 都要有、而不是只留 half 那条：D3D11 上 HLSL 的 <c>half</c>
        /// 就是 float，于是「写成 half3 的 payload」实际按 fp32 算、也按 fp32 存
        /// （RT 是 <c>ARGBHalf</c> 时只有**存**那一步量化到 fp16）。
        /// 在写出前就完成减法的档位（累加自检的 3 档）里，差值本身是 fp32 算出来的，
        /// 拿 half ulp 去数它只会得到「0.000 个 ulp」—— 一个把最强的通过说成
        /// 「测不到」的读数。归因需要的是 fp32 那把尺子。
        ///
        /// 从 <c>VistaApVariantAgreementSelfTest</c> 的私有方法提上来的：
        /// 它在那里数深度的量化步长，与这里数舍入误差是同一条数值事实 ——
        /// 按本文件的规矩不允许存在两份。
        /// </summary>
        public static float Fp32Ulp(float v)
        {
            v = Mathf.Abs(v);
            const float minNormal = 1.1754944e-38f;   // 2^-126
            if (v < minNormal) return 1.4e-45f;       // 最小非规格化
            int e = Mathf.FloorToInt(Mathf.Log(v, 2f));
            return Mathf.Pow(2f, e - 23);             // fp32 有 23 位尾数
        }
    }
}
