using UnityEngine;

namespace Vista.Editor
{
    /// <summary>
    /// 多个自检共用的数值事实。
    ///
    /// 为什么要有这个文件：本项目有一条贯穿始终的规矩 ——
    /// **同一个量不允许存在两份实现**。<c>HalfUlp</c> 是一条纯数值事实，
    /// <c>k_ReadbackFloor</c> 是一条**实测**常量；两者一旦在两个自检里各写一份，
    /// 就会出现「一边更新了、另一边没更新」的状态，而那种偏差的症状恰好是
    /// 「某一条判据的门限比另一条松」—— 最难被发现的一类。
    ///
    /// 这里只放**跨自检共享**的东西。某条自检自己的布景常量、放大系数、
    /// 档位编号一律留在它自己的文件里：把它们集中过来只会让每条自检
    /// 都要去别处才能读懂自己的门限。
    /// </summary>
    static class VistaSelfTestNumerics
    {
        /// <summary>
        /// 渲染 → 读回路径的加性扰动幅度，实测值 = 1/1024。
        ///
        /// 怎么量到的：在 <c>VistaLitAccumulationSelfTest</c> 的 5 档里写死
        /// (0.25, 0.5, 0.75) 这三个 half 精确值，读回来逐像素低 1~2 个 half ulp，
        /// 且随像素位置变化，全图最大偏离恰好是 9.766e-4。
        /// 也就是说着色器写出的值与 CPU 读到的值之间存在一个**加性**扰动场。
        ///
        /// 为什么这条常量值得单独存在：期望值为 0 的量（相对误差、差值的分子）
        /// 读回来永远被这条地板顶起来，而它的量级又与 fp16 相对精度
        /// （<see cref="k_Fp16Rel"/> = 4.88e-4）几乎相同 —— 累加自检的判据 1
        /// 因此连续多次报出 6.595E-004，我却把尺子的地板当成了被测对象的精度极限。
        /// 教训：**尺子的地板与被测量的期望值同量级时，尺子会自己伪造一个结论。**
        /// 修法不是放宽容差（那会把 1e-3 量级的真实偏差一起放过），
        /// 而是在写出之前把被测量抬到地板之上。
        ///
        /// ── 一条重要的性质：它在「同像素两次渲染之差」里会抵消 ──
        ///
        /// 实测它随**像素位置**变化、在恒定值上也变化，也就是说它是一个
        /// 位置的函数而不是值的函数。于是两次渲染在同一像素上相减时，
        /// 同一个扰动量出现在被减数与减数里，一阶上抵消。
        /// 这是 #15 判据②「同一变体渲两遍」那个对照存在的理由：
        /// 对照读到 0，就证明了抵消成立，A-vs-B 的差异不必为这条地板买单。
        /// 反过来，若这条场其实还带一个**值相关**的分量，对照无法把它区分出来 ——
        /// 那一部分由 fp16 量化项负责兜住。
        /// </summary>
        public const float k_ReadbackFloor = 9.766e-4f;

        /// <summary>
        /// fp16 的相对精度 2^-11。一次舍入的误差上界是它的一半，
        /// 但作为**上界**用整个 ulp，方向是保守的。
        /// </summary>
        public const float k_Fp16Rel = 4.88e-4f;

        /// <summary>
        /// half 在 v 附近的一个 ulp。用来回答「差了几个最小可表示单位」。
        /// </summary>
        public static float HalfUlp(float v)
        {
            v = Mathf.Abs(v);
            const float minNormal = 6.1035156e-5f;    // 2^-14
            const float denormStep = 5.9604645e-8f;   // 2^-24
            if (v < minNormal) return denormStep;
            int e = Mathf.FloorToInt(Mathf.Log(v, 2f));
            return Mathf.Pow(2f, e - 10);             // half 有 10 位尾数
        }
    }
}
